'use strict';

const { formatBytes, percent } = require('./format');
const { grade } = require('./evaluate');

/** Shareable Markdown storage report. Paths are shown relative to ~ so usernames are not leaked. */
function buildMarkdownReport({ machine, capacity, apfs, snapshots, hidden, evaluation, home, now = new Date() }) {
  const tilde = (p) => (home && p.startsWith(home) ? '~' + p.slice(home.length) : p);
  const g = grade(evaluation.score);
  const used = capacity.total - capacity.free;
  const lines = [];
  lines.push(`# Silt storage report`);
  lines.push('');
  lines.push(`${now.toISOString().slice(0, 10)} · ${machine?.model ?? 'Mac'} · macOS ${machine?.macos ?? ''}`);
  lines.push('');
  lines.push(`**Storage health: ${evaluation.score}/100 (${g.label})**`);
  lines.push('');
  lines.push(`| | |`);
  lines.push(`|---|---|`);
  lines.push(`| Capacity | ${formatBytes(capacity.total)} |`);
  lines.push(`| Used | ${formatBytes(used)} (${percent(used, capacity.total)}) |`);
  lines.push(`| Free | ${formatBytes(capacity.free)} |`);
  lines.push(`| Purgeable | ${formatBytes(capacity.purgeable)} |`);
  lines.push(`| Available incl. purgeable | ${formatBytes(capacity.availableWithPurgeable)} |`);
  lines.push('');

  if (evaluation.findings.length) {
    lines.push(`## Findings`);
    lines.push('');
    for (const f of evaluation.findings) {
      lines.push(`- **${f.severity.toUpperCase()}** — ${f.title}. ${f.detail}`);
      if (f.action?.type === 'command') lines.push(`  - Fix: \`${f.action.command}\``);
    }
    lines.push('');
  }

  if (apfs?.volumes?.length) {
    lines.push(`## APFS volumes (container ${apfs.container})`);
    lines.push('');
    lines.push(`| Volume | Role | Size |`);
    lines.push(`|---|---|---|`);
    for (const v of apfs.volumes) lines.push(`| ${v.name} | ${v.role} | ${formatBytes(v.bytes)} |`);
    lines.push('');
  }

  if (snapshots?.snapshots?.length) {
    lines.push(`## Local snapshots`);
    lines.push('');
    for (const s of snapshots.snapshots) lines.push(`- ${s.name} (${s.kind})`);
    lines.push('');
  }

  if (hidden) {
    lines.push(`## Hidden data`);
    lines.push('');
    lines.push(
      `Explained: ${formatBytes(hidden.totals.explained)} · Safe to reclaim: ${formatBytes(hidden.totals.reclaimableSafe)} · Worth reviewing: ${formatBytes(
        hidden.totals.reclaimableReview,
      )}`,
    );
    lines.push('');
    lines.push(`| Item | Size | Safety | Location |`);
    lines.push(`|---|---|---|---|`);
    for (const item of hidden.items.filter((i) => i.bytes > 0)) {
      const where = item.paths.length === 1 ? tilde(item.paths[0].path) : `${item.paths.length} locations`;
      lines.push(`| ${item.name} | ${formatBytes(item.bytes)} | ${item.safety} | \`${where}\` |`);
    }
    lines.push('');
  } else {
    lines.push(`_Run a System Data scan in Silt to include hidden data in this report._`);
    lines.push('');
  }
  lines.push(`---`);
  lines.push(`Generated by [Silt](https://github.com/thestealthgoat/Mac-cleaning) — open-source storage analyzer for macOS.`);
  return lines.join('\n');
}

module.exports = { buildMarkdownReport };
